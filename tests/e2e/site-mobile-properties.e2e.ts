import { expect, test } from '@playwright/test'
import { canvasFrame, canvasFrameForBreakpoint, createPage, insertNotchModule, openSiteEditor, setPropValue } from './helpers'

test.use({ hasTouch: true })

test('changes padding on a phone and returns to the selected block (BUILDER-006)', async ({ page }) => {
  const slug = `studio-spacing-${Date.now()}`
  const hours = 'Saturday, 11 am to 3 pm.'
  await openSiteEditor(page)
  await createPage(page, slug, slug)
  await insertNotchModule(page, 'text')
  await setPropValue(page, 'text', hours)
  await expect(canvasFrame(page).getByText(hours)).toBeVisible()
  await page.getByRole('button', { name: 'Undock Properties panel' }).click()

  await page.setViewportSize({ width: 320, height: 568 })
  await page.goto(`/admin/site?page=${slug}`)
  const block = canvasFrameForBreakpoint(page, 'mobile').getByText(hours, { exact: true })
  const add = page.getByRole('button', { name: 'Add to canvas', exact: true })
  const actionHeight = await add.evaluate(el => getComputedStyle(el).height)
  await expect(page.getByRole('button', { name: /^Editing context:/ })).toHaveCSS('height', actionHeight)
  await expect(page.getByTestId('canvas-notch-undo-btn')).toHaveCSS('height', actionHeight)
  const initialBounds = await block.boundingBox()
  await block.tap()
  const properties = page.getByRole('button', { name: 'Properties', exact: true })
  await properties.tap()
  const panel = page.getByTestId('properties-panel')
  await expect(panel).toHaveCSS('width', '320px')
  await panel.getByRole('button', { name: 'Style inline', exact: true }).tap()
  await panel.getByRole('combobox', { name: 'Style section' }).tap()
  await page.getByRole('option', { name: 'Spacing', exact: true }).tap()
  const top = panel.getByRole('textbox', { name: 'padding top', exact: true })
  await expect(top).toBeInViewport()
  await expect(top).toHaveCSS('height', actionHeight)
  await expect(panel.getByRole('button', { name: 'Back to canvas' })).toHaveCSS('height', actionHeight)
  await expect(panel.getByRole('button', { name: 'Componentize', exact: true })).toHaveCSS('height', actionHeight)
  await top.tap()
  await top.fill('32px')
  await panel.getByRole('button', { name: 'Back to canvas' }).tap()
  await expect(panel).toBeHidden()
  await expect(page.getByTestId('canvas-root')).toBeFocused()
  await expect(properties).toBeVisible()
  await expect(block).toHaveCSS('padding-top', '32px')
  await expect(block).toHaveCSS('padding-bottom', '0px')
  expect((await block.boundingBox())?.y).toBe(initialBounds?.y)
  await page.reload()
  await expect(block).toHaveCSS('padding-top', '32px')

  await block.tap()
  await properties.tap()
  await expect(panel).toHaveAttribute('data-variant', 'docked')
  await page.setViewportSize({ width: 1280, height: 900 })
  await expect(panel).toHaveAttribute('data-variant', 'floating')
})
