import { expect, test } from '@playwright/test'
import { canvasFrameForBreakpoint, createPage, insertNotchModule, openSiteEditor } from './helpers'

test('folds the insert and breakpoint notches as panels narrow the canvas (SITE-010)', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 800 })
  await openSiteEditor(page)
  await createPage(page, 'Canvas controls', `notches-${Date.now()}`)
  await insertNotchModule(page, 'text')
  const notch = page.getByTestId('canvas-notch')
  const context = page.getByRole('button', { name: 'Editing context: Desktop' })
  await expect(context).toBeVisible()
  const favorite = notch.getByRole('button', { name: 'Add Text', exact: true })
  await expect(favorite).toBeVisible()
  await favorite.focus()
  await page.setViewportSize({ width: 1100, height: 800 })
  await expect(favorite).toHaveCount(0)
  await expect(notch.getByRole('button')).toHaveCount(3)
  const suffix = context.locator('[data-notch-fold]')
  await expect(suffix).toHaveCSS('width', '0px')
  await expect(notch.getByRole('button', { name: 'Add to canvas' })).toBeFocused()

  // Keep the browser width fixed. The space recovered from Explorer alone
  // must restore both the favorite buttons and the viewport label.
  await page.getByTestId('panel-rail-explorer').click()
  await expect(favorite).toBeVisible()
  await expect.poll(() => suffix.evaluate(el => el.clientWidth)).toBeGreaterThan(40)
  await page.getByTestId('panel-rail-explorer').click()
  await expect(favorite).toHaveCount(0)
  await expect(notch.getByRole('button', { name: 'Add to canvas' })).toBeInViewport()

  await context.click()
  await expect(page.getByRole('menu', { name: 'Editing context' })).toBeVisible()
  await page.getByRole('menuitem', { name: 'Manage contexts…' }).click()
  await page.getByRole('menuitem', { name: 'Edit Desktop breakpoint' }).click()
  await expect(page.getByRole('dialog', { name: 'Edit viewport' })).toBeVisible()
  await page.keyboard.press('Escape')
  await context.click()
  await page.getByRole('menuitem', { name: 'Manage contexts…' }).click()
  await page.getByRole('menuitem', { name: 'Add context…' }).click()
  const newContext = page.getByRole('dialog', { name: 'Add context' })
  await newContext.getByRole('button', { name: 'Environment media query' }).click()
  await page.keyboard.press('Escape')
  const add = notch.getByRole('button', { name: 'Add to canvas' })
  await add.click()
  const picker = page.getByRole('dialog', { name: 'Add to canvas' })
  await picker.locator('[data-module-id="base.text"]').first().click()
  await expect(picker).toBeHidden()
  await notch.getByRole('button', { name: 'Undo' }).click()
  await notch.getByRole('button', { name: 'Redo' }).click()
})

test('keeps the selected block in view for a Mobile spacing override and the return to Desktop (SITE-010)', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 800 })
  await openSiteEditor(page)
  await createPage(page, 'Responsive spacing', `responsive-spacing-${Date.now()}`)
  await insertNotchModule(page, 'text')
  const className = 'responsive-title'
  await page.getByTestId('class-picker-input').fill(className)
  await page.getByTestId('class-picker-submit').click()
  const block = (id: string) => canvasFrameForBreakpoint(page, id).locator(`.${className}`)
  const panel = page.getByTestId('properties-panel')
  const padding = panel.getByRole('textbox', { name: 'padding bottom', exact: true })
  await padding.fill('8px')
  await padding.blur()

  await page.setViewportSize({ width: 1100, height: 800 })
  const trigger = page.getByRole('button', { name: /^Editing context:/ })
  await trigger.focus()
  await page.keyboard.press('ArrowDown')
  const menu = page.getByRole('menu', { name: 'Editing context' })
  const desktop = menu.getByRole('menuitemradio', { name: /Desktop/ })
  const mobile = menu.getByRole('menuitemradio', { name: /Mobile/ })
  await expect(desktop).toBeChecked()
  await expect(desktop).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await expect(trigger).toBeFocused()
  await expect(panel).toBeVisible()
  await page.keyboard.press('ArrowDown')
  await expect(desktop).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('ArrowDown')
  await expect(mobile).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(trigger).toBeFocused()
  // The iframe can be inside the browser viewport but clipped by Explorer.
  // Check the actual canvas edges after the pan has settled in both directions.
  const root = page.getByTestId('canvas-root')
  async function expectVisibleBlock(id: string) {
    await expect.poll(async () => {
      const canvas = await root.boundingBox()
      const node = await block(id).boundingBox()
      if (!canvas || !node) return false
      const visible = Math.min(node.x + node.width, canvas.x + canvas.width) - Math.max(node.x, canvas.x)
      return visible >= Math.min(node.width, canvas.width) - 1
    }).toBe(true)
  }
  await expectVisibleBlock('mobile')
  await expect(panel.getByText('Mobile', { exact: true })).toBeVisible()
  await padding.fill('32px')
  await padding.blur()
  await expect(block('mobile')).toHaveCSS('padding-bottom', '32px')
  await expect(block('desktop')).toHaveCSS('padding-bottom', '8px')
  await trigger.click()
  await expect(mobile).toBeChecked()
  await desktop.click()
  await expectVisibleBlock('desktop')
  await expect(panel.getByText('Base styles', { exact: true })).toBeVisible()
  await expect(padding).toHaveValue('8px')
})
