import { expect, test } from '@playwright/test'
import { canvasFrame, canvasFrameForBreakpoint, createPage, insertNotchModule, openSiteEditor, setPropValue } from './helpers'

test.use({ hasTouch: true })

test('finds a block by touch and returns to its insertion point on a long page (SITE-005)', async ({ page }) => {
  const slug = `phone-block-picker-${Date.now()}`
  const studioNotes = 'See the work in progress at the studio. '.repeat(65).trim()
  await openSiteEditor(page)
  await createPage(page, slug, slug)
  await insertNotchModule(page, 'text')
  await setPropValue(page, 'text', studioNotes)
  await expect(canvasFrame(page).getByText(studioNotes)).toBeVisible()
  await page.setViewportSize({ width: 320, height: 568 })
  await page.goto(`/admin/site?page=${slug}`)

  const frame = canvasFrameForBreakpoint(page, 'mobile')
  await expect(frame.getByText(studioNotes)).toBeVisible()
  const add = page.getByTestId('canvas-notch-add-btn')
  await expect(add).toHaveText('Add')
  await add.tap()
  const dialog = page.getByRole('dialog', { name: 'Add to canvas' })
  const close = dialog.getByRole('button', { name: 'Close block picker' })
  const search = dialog.getByRole('searchbox', { name: 'Search modules' })
  await expect(close).toBeFocused()
  await expect(dialog.getByRole('button', { name: 'List view' })).toHaveAttribute('aria-pressed', 'true')
  await close.tap()
  await expect(dialog).toBeHidden()
  await expect(add).toBeFocused()

  await add.tap()
  await search.tap()
  await search.fill('zzzz')
  await expect(dialog.getByText('No matches', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Clear search' }).tap()
  await search.fill('button')
  await dialog.locator('[data-module-id="base.button"]').tap()
  const inserted = frame.getByRole('button', { name: 'Get Started', exact: true })
  await expect(dialog).toBeHidden()
  await expect(page.getByTestId('properties-panel')).toBeHidden()
  await expect(page.getByTestId('canvas-root')).toBeFocused()
  await expect(inserted).toBeInViewport({ ratio: 0.9 })

  await add.tap()
  await dialog.getByRole('button', { name: 'Recent', exact: true }).tap()
  await expect(dialog.locator('[data-module-id="base.button"]')).toBeInViewport()
  await close.tap()
  await page.getByRole('button', { name: 'Undo', exact: true }).tap()
  await expect(inserted).toHaveCount(0)
  await page.getByRole('button', { name: 'Redo', exact: true }).tap()
  await expect(inserted).toHaveCount(1)
  await page.reload()
  await expect(inserted).toHaveCount(1)
})
